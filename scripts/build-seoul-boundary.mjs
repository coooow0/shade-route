import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const inputPath = resolve(root, "data-src/seoul-boundary.geojson");
const outputPath = resolve(root, "src/data/seoulBoundary.ts");
const TOLERANCE = 0.00015;

function squaredDistanceToSegment(point, start, end) {
  let x = start[0];
  let y = start[1];
  let dx = end[0] - x;
  let dy = end[1] - y;
  if (dx !== 0 || dy !== 0) {
    const t =
      ((point[0] - x) * dx + (point[1] - y) * dy) / (dx * dx + dy * dy);
    if (t > 1) {
      x = end[0];
      y = end[1];
    } else if (t > 0) {
      x += dx * t;
      y += dy * t;
    }
  }
  dx = point[0] - x;
  dy = point[1] - y;
  return dx * dx + dy * dy;
}

function simplifyLine(points, tolerance) {
  if (points.length <= 3) return points;
  const first = points[0];
  const last = points[points.length - 1];
  let maxDistance = 0;
  let splitIndex = 0;
  for (let index = 1; index < points.length - 1; index++) {
    const distance = squaredDistanceToSegment(points[index], first, last);
    if (distance > maxDistance) {
      maxDistance = distance;
      splitIndex = index;
    }
  }
  if (maxDistance <= tolerance * tolerance) return [first, last];
  return [
    ...simplifyLine(points.slice(0, splitIndex + 1), tolerance).slice(0, -1),
    ...simplifyLine(points.slice(splitIndex), tolerance),
  ];
}

function simplifyRing(ring) {
  const open = ring[0][0] === ring.at(-1)[0] && ring[0][1] === ring.at(-1)[1]
    ? ring.slice(0, -1)
    : ring;
  const simplified = simplifyLine([...open, open[0]], TOLERANCE);
  return simplified.map(([lon, lat]) => [
    Number(lon.toFixed(6)),
    Number(lat.toFixed(6)),
  ]);
}

const source = JSON.parse(await readFile(inputPath, "utf8"));
const polygons =
  source.type === "MultiPolygon"
    ? source.coordinates
    : source.type === "Polygon"
      ? [source.coordinates]
      : null;
if (!polygons) throw new Error("Invalid Seoul boundary geometry");
const simplified = polygons.map((polygon) => polygon.map(simplifyRing));
const sourcePoints = polygons.flat(2).length;
const outputPoints = simplified.flat(2).length;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by scripts/build-seoul-boundary.mjs\nexport type BoundaryPosition = readonly [longitude: number, latitude: number];\nexport type BoundaryRing = ReadonlyArray<BoundaryPosition>;\nexport type BoundaryPolygon = ReadonlyArray<BoundaryRing>;\n\nexport const SEOUL_BOUNDARY: ReadonlyArray<BoundaryPolygon> = ${JSON.stringify(simplified)};\n`,
);
