import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

const TOLERANCE = 0.00015;

export function boundaryCoordinates(boundary) {
  if (boundary?.type === "MultiPolygon") return boundary.coordinates;
  if (boundary?.type === "Polygon") return [boundary.coordinates];
  throw new Error("Invalid Seoul boundary geometry");
}

export function publicBoundaryPayload(source) {
  return `${JSON.stringify({ schema: 1, coordinates: boundaryCoordinates(source) })}\n`;
}

function squaredDistanceToSegment(point, start, end) {
  let x = start[0];
  let y = start[1];
  let dx = end[0] - x;
  let dy = end[1] - y;
  if (dx !== 0 || dy !== 0) {
    const t = ((point[0] - x) * dx + (point[1] - y) * dy) / (dx * dx + dy * dy);
    if (t > 1) {
      x = end[0];
      y = end[1];
    } else if (t > 0) {
      x += dx * t;
      y += dy * t;
    }
  }
  dx = point[0] - x;
  dy = point[1] - y;
  return dx * dx + dy * dy;
}

function simplifyLine(points, tolerance) {
  if (points.length <= 3) return points;
  const first = points[0];
  const last = points[points.length - 1];
  let maxDistance = 0;
  let splitIndex = 0;
  for (let index = 1; index < points.length - 1; index++) {
    const distance = squaredDistanceToSegment(points[index], first, last);
    if (distance > maxDistance) {
      maxDistance = distance;
      splitIndex = index;
    }
  }
  if (maxDistance <= tolerance * tolerance) return [first, last];
  return [
    ...simplifyLine(points.slice(0, splitIndex + 1), tolerance).slice(0, -1),
    ...simplifyLine(points.slice(splitIndex), tolerance),
  ];
}

function simplifyRing(ring) {
  if (!Array.isArray(ring) || ring.length < 4) {
    throw new Error("Invalid Seoul boundary ring");
  }
  const first = ring[0];
  const last = ring.at(-1);
  const open =
    first[0] === last[0] && first[1] === last[1] ? ring.slice(0, -1) : ring;
  const simplified = simplifyLine([...open, open[0]], TOLERANCE);
  return simplified.map(([lon, lat]) => [
    Number(lon.toFixed(6)),
    Number(lat.toFixed(6)),
  ]);
}

export function runtimeBoundaryModulePayload(source) {
  const polygons = boundaryCoordinates(source);
  const simplified = polygons.map((polygon) => polygon.map(simplifyRing));
  const sourcePoints = polygons.flat(2).length;
  const outputPoints = simplified.flat(2).length;
  const payload = `// Generated by scripts/seoul-boundary-artifacts.mjs. Do not edit by hand.\nexport type BoundaryPosition = readonly [longitude: number, latitude: number];\nexport type BoundaryRing = ReadonlyArray<BoundaryPosition>;\nexport type BoundaryPolygon = ReadonlyArray<BoundaryRing>;\n\nexport const SEOUL_BOUNDARY: ReadonlyArray<BoundaryPolygon> = ${JSON.stringify(simplified)};\n`;
  return { payload, sourcePoints, outputPoints };
}

export async function writeRuntimeBoundaryArtifact(sourcePath, outputPath) {
  const source = JSON.parse(await readFile(sourcePath, "utf8"));
  const result = runtimeBoundaryModulePayload(source);
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, result.payload);
  return result;
}

export async function verifyRuntimeBoundaryArtifact(sourcePath, outputPath) {
  const [sourcePayload, actualPayload] = await Promise.all([
    readFile(sourcePath, "utf8"),
    readFile(outputPath, "utf8"),
  ]);
  let expected;
  try {
    expected = runtimeBoundaryModulePayload(JSON.parse(sourcePayload)).payload;
  } catch {
    throw new Error("ARTIFACT_VERIFY_FAILED:runtime-boundary-source");
  }
  if (actualPayload !== expected) {
    throw new Error("ARTIFACT_VERIFY_FAILED:runtime-boundary");
  }
}

export async function verifyPublicBoundaryArtifact(sourcePath, outputPath) {
  const [sourcePayload, actualPayload] = await Promise.all([
    readFile(sourcePath, "utf8"),
    readFile(outputPath, "utf8"),
  ]);
  let expected;
  try {
    expected = publicBoundaryPayload(JSON.parse(sourcePayload));
  } catch {
    throw new Error("ARTIFACT_VERIFY_FAILED:public-boundary-source");
  }
  if (actualPayload !== expected) {
    throw new Error("ARTIFACT_VERIFY_FAILED:public-boundary");
  }
}
